#!/usr/bin/env python
"""Regenerate docs/experiments.md from experiments/results.csv and experiments/*/notes.md."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from acoustic_separator import tracking  # noqa: E402

COLS = [("experiment", "exp"), ("strategy", "strat"), ("models", "models"), ("sdr", "SDR"),
        ("si_sdr", "SI-SDR"), ("sir", "SIR"), ("sar", "SAR"), ("target_retention", "retention"),
        ("leakage", "leak dB"), ("hard_sdr", "hard SDR"), ("target_guitar_prob", "tgt gtr p"),
        ("runtime_target_s", "tgt s"), ("is_champion", "champ")]


def fmt(v: str) -> str:
    try:
        f = float(v)
        return f"{f:.2f}" if abs(f) < 1000 else f"{f:.0f}"
    except (TypeError, ValueError):
        return v or ""


def main() -> int:
    rows = tracking.read_results()
    champ = tracking.current_champion()
    lines = ["# Experiment log", "",
             "Generated by `scripts/summarize_experiments.py` from `experiments/results.csv` and "
             "each `experiments/<id>/notes.md`. Metrics are means over the ground-truth "
             "validation set (`datasets/validation`, see `docs/research.md` §4); `tgt gtr p` is the "
             "reference-free AST guitar probability on the target song (proxy only).", ""]
    if champ:
        lines += [f"**Current Champion:** `{champ['experiment']}` — validation SDR "
                  f"{champ['metrics'].get('sdr_mean', float('nan')):.3f} dB "
                  f"(promoted {champ['promoted_at']}).", ""]
    lines += ["| " + " | ".join(h for _, h in COLS) + " |", "|" + "---|" * len(COLS)]
    for r in rows:
        lines.append("| " + " | ".join(fmt(r.get(k, "")) for k, _ in COLS) + " |")
    lines += ["", "## Per-experiment notes", ""]
    for d in sorted((ROOT / "experiments").glob("exp[0-9][0-9][0-9]_*")):
        notes = d / "notes.md"
        if notes.exists():
            body = notes.read_text().strip().split("\n")
            lines += ["#" + body[0], *body[1:], ""]
            mfile = d / "metrics.json"
            if mfile.exists():
                m = json.loads(mfile.read_text()).get("validation", {})
                cats = m.get("by_category", {})
                if cats:
                    lines += ["| category | SDR | SI-SDR | retention | leak dB |", "|---|---|---|---|---|"]
                    lines += [f"| {c} | {v['sdr']:.2f} | {v['si_sdr']:.2f} | {v['target_retention']:.3f} | "
                              f"{v['leakage_db']:.2f} |" for c, v in cats.items()]
                    lines.append("")
    out = ROOT / "docs" / "experiments.md"
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
